r"""
Rule profiles: named, prioritized groups of text-extraction rules.

The rules that :py:class:`~pylatexenc.latex2text.LatexNodes2Text` applies are
held in a :py:class:`~pylatexenc.macrospec.LatexContextDb`, where every
definition belongs to a *category*.  The three kinds of definitions -- macros,
environments and latex specials -- live in three separate lookup tables, and a
definition in an earlier category shadows the definitions of the same name in
the later categories.  This module builds on that mechanism to offer a layer
suited to collections of documents (say, different journals) that each provide
their own extraction rules:

- A :py:class:`RuleProfile` is a named group of rules.  A profile typically
  redefines only a handful of names; every name it does not mention is left to
  the underlying default rules.  Its macro, environment and specials rules are
  kept in three separate lists, so that overriding a macro never touches the
  environment or specials tables.

- A :py:class:`RuleProfileDb` collects the profiles, assigns each of them a
  priority, and builds a concrete
  :py:class:`~pylatexenc.macrospec.LatexContextDb` for any selection of
  profiles.  When several enabled profiles define the same name, the profile
  with the highest priority wins; the definitions that lose out are not lost,
  they are merely shadowed and become effective again as soon as the winning
  profile is disabled or removed.

Nothing in this module is global: a context database is built for one document
from a profile selection, and a second document converted with a different
selection gets its own database.  The two documents do not share any state.

The objects stored in a profile may be of any type that a
:py:class:`~pylatexenc.macrospec.LatexContextDb` accepts.  In practice you keep
two :py:class:`RuleProfileDb` instances, mirroring the two context databases
that :py:mod:`pylatexenc.latexwalker` and :py:mod:`pylatexenc.latex2text`
already use: one holding parser specifications
(:py:class:`~pylatexenc.macrospec.MacroSpec` and friends) and one holding text
specifications (:py:class:`MacroTextSpec` and friends).
"""



# The prefix of the context-db category that a profile is turned into.  It must
# not collide with a user's own category names nor with the internal,
# autogenerated prefix '__lctxdb_cat_'.
_rule_profile_category_prefix = 'rule-profile:'


class RuleProfile(object):
    r"""
    A named group of macro, environment and/or latex-specials rules.

    A profile is meant to capture the rules of one source (one journal, say).
    It usually redefines only a few names, for instance a single macro; all the
    names it does not list keep whatever definition the base context or a
    lower-priority profile gives them.

    The arguments `macros`, `environments` and `specials` are iterables of
    specification objects, exactly as accepted by
    :py:meth:`~pylatexenc.macrospec.LatexContextDb.add_context_category()`.
    For a text-conversion profile these are
    :py:class:`MacroTextSpec`, :py:class:`EnvironmentTextSpec` and
    :py:class:`SpecialsTextSpec` instances, respectively; the three kinds are
    stored independently of one another, so a profile that overrides a macro
    contains no environment or specials definition unless it is given some.

    A profile is immutable once constructed: register it on a
    :py:class:`RuleProfileDb` rather than changing it in place.
    """
    def __init__(self, name, description=None, macros=None, environments=None,
                 specials=None):
        super(RuleProfile, self).__init__()

        if name is None or not isinstance(name, str) or not name:
            raise ValueError("RuleProfile: a non-empty string name is required")

        self.name = name
        self.description = description

        macros = list(macros) if macros else []
        environments = list(environments) if environments else []
        specials = list(specials) if specials else []

        self._check_specs(macros, 'macros', 'macroname')
        self._check_specs(environments, 'environments', 'environmentname')
        self._check_specs(specials, 'specials', 'specials_chars')

        self._macros = macros
        self._environments = environments
        self._specials = specials

    @staticmethod
    def _check_specs(specs, which, attrname):
        # Every spec must expose the attribute the context database indexes it
        # on, and the names must be unique within the profile: a profile that
        # lists the same name twice would keep only one of the two entries
        # silently, which is almost certainly a mistake.
        seen = []
        for spec in specs:
            if not hasattr(spec, attrname):
                raise ValueError(
                    "RuleProfile: every entry of {!r} must have a {!r} "
                    "attribute".format(which, attrname)
                )
            key = getattr(spec, attrname)
            if key in seen:
                raise ValueError(
                    "RuleProfile: duplicate {} name {!r} in profile".format(
                        which, key
                    )
                )
            seen.append(key)

    @property
    def macros(self):
        r"""The list of macro specification objects of this profile."""
        return list(self._macros)

    @property
    def environments(self):
        r"""The list of environment specification objects of this profile."""
        return list(self._environments)

    @property
    def specials(self):
        r"""The list of specials specification objects of this profile."""
        return list(self._specials)

    def macro_names(self):
        r"""Return the macro names that this profile defines."""
        return [m.macroname for m in self._macros]

    def environment_names(self):
        r"""Return the environment names that this profile defines."""
        return [e.environmentname for e in self._environments]

    def specials_chars(self):
        r"""Return the specials character sequences that this profile defines."""
        return [s.specials_chars for s in self._specials]

    def get_macro_spec(self, macroname):
        r"""Return the macro spec registered under `macroname`, or `None`."""
        for spec in self._macros:
            if spec.macroname == macroname:
                return spec
        return None

    def get_environment_spec(self, environmentname):
        r"""Return the environment spec registered under `environmentname`, or `None`."""
        for spec in self._environments:
            if spec.environmentname == environmentname:
                return spec
        return None

    def get_specials_spec(self, specials_chars):
        r"""Return the specials spec registered under `specials_chars`, or `None`."""
        for spec in self._specials:
            if spec.specials_chars == specials_chars:
                return spec
        return None

    def __repr__(self):
        return (
            "<RuleProfile {!r}: {} macro(s), {} environment(s), "
            "{} specials>".format(
                self.name,
                len(self._macros),
                len(self._environments),
                len(self._specials),
            )
        )


class ShadowedRule(object):
    r"""
    A definition that lost the precedence contest for a name.

    .. py:attribute:: profile

       The name of the profile that provided the shadowed definition.

    .. py:attribute:: spec

       The specification object that would apply if the winning profiles were
       removed.
    """
    def __init__(self, profile, spec):
        super(ShadowedRule, self).__init__()
        self.profile = profile
        self.spec = spec


class RuleResolution(object):
    r"""
    How the effective rule for one name is determined.

    .. py:attribute:: which

       One of ``'macros'``, ``'environments'`` or ``'specials'``; the naming
       domain the rule belongs to.  The three domains are resolved
       independently of one another.

    .. py:attribute:: key

       The macro name, environment name or specials character sequence.

    .. py:attribute:: spec

       The specification that actually applies -- the winning one.

    .. py:attribute:: profile

       Where the winning specification comes from: the name of the winning
       profile, or `None` if it comes from the base context database.

    .. py:attribute:: shadowed

       A list of :py:class:`ShadowedRule` instances, ordered from the next
       candidate down.  The first entry is the rule that would take over if the
       winning profile were disabled or removed.
    """
    def __init__(self, which, key, spec, profile, shadowed=None):
        super(RuleResolution, self).__init__()
        self.which = which
        self.key = key
        self.spec = spec
        self.profile = profile
        self.shadowed = list(shadowed) if shadowed else []

    def __repr__(self):
        return "<RuleResolution {} {!r} -> {!r}{}>".format(
            self.which,
            self.key,
            self.profile,
            " ({} shadowed)".format(len(self.shadowed)) if self.shadowed else ""
        )


class RuleProfileDb(object):
    r"""
    A collection of named :py:class:`RuleProfile` instances with priorities.

    Profiles are registered with :py:meth:`add_profile()`, each with an integer
    priority (zero by default); the larger the number, the earlier the profile
    is searched when several enabled profiles define the same name.  Profiles
    at the same priority keep their registration order, the earlier one
    winning.  A profile is disabled simply by leaving it out of the `enabled`
    selection of :py:meth:`build_context()`; it is removed altogether with
    :py:meth:`remove_profile()`.
    """
    def __init__(self):
        super(RuleProfileDb, self).__init__()
        self._profiles = {}
        self._profile_order = []
        self._priorities = {}

    #-- registration ---------------------------------------------------------

    def add_profile(self, profile, priority=0):
        r"""
        Register `profile`, a :py:class:`RuleProfile`, with the given `priority`.

        A larger priority means the profile's definitions take precedence over
        those of profiles with a smaller priority whenever they define the same
        name.  The profile name must not already be registered; use
        :py:meth:`remove_profile()` first to replace one.
        """
        if not isinstance(profile, RuleProfile):
            raise ValueError(
                "add_profile(): expected a RuleProfile instance, got {!r}"
                .format(profile)
            )
        if profile.name in self._profiles:
            raise ValueError(
                "A profile named {!r} is already registered".format(profile.name)
            )
        self._profiles[profile.name] = profile
        self._profile_order.append(profile.name)
        self._priorities[profile.name] = priority
        return self

    def remove_profile(self, name):
        r"""
        Remove the profile called `name` and return it.

        Raises `KeyError` if no such profile is registered.  Any name that the
        removed profile used to provide is resolved again from the remaining
        profiles or the base context, so a lower-priority rule that was being
        shadowed becomes effective on the next :py:meth:`build_context()` call.
        """
        if name not in self._profiles:
            raise KeyError(
                "No rule profile named {!r} is registered".format(name)
            )
        profile = self._profiles.pop(name)
        del self._priorities[name]
        new_order = []
        for n in self._profile_order:
            if n != name:
                new_order.append(n)
        self._profile_order = new_order
        return profile

    def set_priority(self, name, priority):
        r"""
        Change the `priority` of the already registered profile called `name`.

        Raises `KeyError` if the profile does not exist.
        """
        if name not in self._profiles:
            raise KeyError(
                "No rule profile named {!r} is registered".format(name)
            )
        self._priorities[name] = priority
        return self

    #-- introspection --------------------------------------------------------

    def profile_names(self):
        r"""Return the names of the registered profiles, in registration order."""
        return list(self._profile_order)

    def get_profile(self, name):
        r"""Return the registered profile called `name`, or `None`."""
        return self._profiles.get(name)

    def get_priority(self, name):
        r"""Return the priority of the profile called `name`."""
        if name not in self._priorities:
            raise KeyError(
                "No rule profile named {!r} is registered".format(name)
            )
        return self._priorities[name]

    def _check_enabled(self, enabled):
        # Turn an `enabled` argument into a list of profile names, validating
        # that each of them exists.  `None` means every registered profile.
        if enabled is None:
            return list(self._profile_order)
        names = list(enabled)
        for name in names:
            if name not in self._profiles:
                raise KeyError(
                    "No rule profile named {!r} is registered".format(name)
                )
        return names

    def active_profiles(self, enabled=None):
        r"""
        Return the enabled profiles as ``(name, priority, profile)`` tuples,
        ordered from the highest precedence to the lowest.

        Precedence is decided by priority first and by registration order for
        profiles that share a priority.  With `enabled` set to `None` every
        registered profile is active; otherwise `enabled` is the iterable of
        profile names to activate.
        """
        names = self._check_enabled(enabled)
        indexed = []
        for order_index, name in enumerate(self._profile_order):
            if name in names:
                indexed.append(
                    (self._priorities[name], order_index, name,
                     self._profiles[name])
                )
        # larger priority first; for equal priorities the smaller registration
        # index (registered earlier) first
        indexed = sorted(indexed, key=lambda item: (-item[0], item[1]))
        return [ (name, prio, profile) for (prio, _idx, name, profile) in indexed ]

    #-- building contexts ----------------------------------------------------

    def build_context(self, base_context, enabled=None, create_class=None):
        r"""
        Build a fresh :py:class:`~pylatexenc.macrospec.LatexContextDb` for one
        document.

        `base_context` is the database of the rules that apply where no enabled
        profile provides one -- typically the one returned by
        :py:func:`pylatexenc.latex2text.get_default_latex_context_db()`.  It is
        copied and never modified, so the same base can serve any number of
        documents.

        `enabled` selects the profiles to activate (`None` activates all of
        them).  Each active profile becomes one context-db category, named
        ``'rule-profile:<profile name>'``, and the categories are ordered by
        precedence so that the highest-priority definition of every name wins.
        Macros, environments and specials remain in their three separate
        tables throughout.

        `create_class` is forwarded to
        :py:meth:`~pylatexenc.macrospec.LatexContextDb.filtered_context()` and
        only matters for custom context-database subclasses.
        """
        active = self.active_profiles(enabled=enabled)

        # Start from a copy of the base context so that the caller's database
        # is never mutated.  Profile categories are prepended one by one, from
        # the lowest precedence to the highest, so that the category list ends
        # up ordered highest-precedence first with the base categories last.
        new_context = base_context.filtered_context(create_class=create_class)

        for _name, _prio, profile in reversed(active):
            new_context.add_context_category(
                _rule_profile_category_prefix + profile.name,
                macros=profile.macros,
                environments=profile.environments,
                specials=profile.specials,
                prepend=True,
            )

        return new_context

    #-- explaining the effective rules --------------------------------------

    def explain(self, base_context, enabled=None):
        r"""
        Resolve every name touched by the enabled profiles (or by the base
        context) and return the result as a dictionary with the keys
        ``'macros'``, ``'environments'`` and ``'specials'``.

        Each value is a dictionary mapping a name to the
        :py:class:`RuleResolution` that explains which specification actually
        applies, which profile (or the base context) provides it, and which
        definitions are currently shadowed.  The three naming domains are
        reported independently.
        """
        result = {
            'macros': {},
            'environments': {},
            'specials': {},
        }
        self._collect_base_rules(base_context, result)

        active = self.active_profiles(enabled=enabled)
        # profiles come highest-precedence first; walk them in reverse so that
        # each new entry is either the new winner or another shadowed rule
        for _name, _prio, profile in reversed(active):
            self._absorb_profile_rules(profile, result)

        return result

    def explain_rule(self, which, key, base_context, enabled=None):
        r"""
        Return the :py:class:`RuleResolution` for one name in one naming
        domain, or `None` if neither the base context nor any enabled profile
        defines it.

        `which` is ``'macros'``, ``'environments'`` or ``'specials'`` and `key`
        is the macro name, environment name or specials character sequence.
        """
        if which not in ('macros', 'environments', 'specials'):
            raise ValueError(
                "explain_rule(): which must be one of 'macros', 'environments', "
                "'specials', got {!r}".format(which)
            )
        all_resolutions = self.explain(base_context, enabled=enabled)
        return all_resolutions[which].get(key)

    @staticmethod
    def _collect_base_rules(base_context, result):
        # Seed the resolution tables with the base context rules.  The base
        # context may itself hold several categories; the first one to define a
        # name is the one the context database would itself return.  An
        # absorption makes the newcomer the winner, so the categories are
        # visited from the lowest precedence to the highest, i.e. in reverse of
        # the category list, leaving the first category as the final winner.
        for cat in reversed(list(base_context.category_list)):
            RuleProfileDb._absorb_dict(
                cat_dict=base_context.d[cat]['macros'],
                which='macros',
                resolutions=result['macros'],
                profile_name=None,
            )
            RuleProfileDb._absorb_dict(
                cat_dict=base_context.d[cat]['environments'],
                which='environments',
                resolutions=result['environments'],
                profile_name=None,
            )
            RuleProfileDb._absorb_dict(
                cat_dict=base_context.d[cat]['specials'],
                which='specials',
                resolutions=result['specials'],
                profile_name=None,
            )

    def _absorb_profile_rules(self, profile, result):
        self._absorb_spec_list(
            specs=profile.macros, which='macros',
            key_attr='macroname', resolutions=result['macros'],
            profile_name=profile.name,
        )
        self._absorb_spec_list(
            specs=profile.environments, which='environments',
            key_attr='environmentname', resolutions=result['environments'],
            profile_name=profile.name,
        )
        self._absorb_spec_list(
            specs=profile.specials, which='specials',
            key_attr='specials_chars', resolutions=result['specials'],
            profile_name=profile.name,
        )

    @staticmethod
    def _absorb_spec_list(specs, which, key_attr, resolutions, profile_name):
        cat_dict = {}
        for spec in specs:
            cat_dict[getattr(spec, key_attr)] = spec
        RuleProfileDb._absorb_dict(
            cat_dict=cat_dict, which=which, resolutions=resolutions,
            profile_name=profile_name,
        )

    @staticmethod
    def _absorb_dict(cat_dict, which, resolutions, profile_name):
        for key, spec in cat_dict.items():
            existing = resolutions.get(key)
            if existing is None:
                resolutions[key] = RuleResolution(
                    which=which, key=key, spec=spec, profile=profile_name
                )
            else:
                # the newcomer is higher precedence than everything seen so
                # far, so it becomes the winner and the previous winner leads
                # the shadowed list
                previous_shadowed = list(existing.shadowed)
                previous_shadowed.insert(
                    0, ShadowedRule(existing.profile, existing.spec)
                )
                resolutions[key] = RuleResolution(
                    which=which,
                    key=key,
                    spec=spec,
                    profile=profile_name,
                    shadowed=previous_shadowed,
                )

    def __repr__(self):
        return "<RuleProfileDb: {} profile(s)>".format(len(self._profiles))
