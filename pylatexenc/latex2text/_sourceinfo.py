# Internal module. Internal API may move, disappear or otherwise change at any
# time and without notice.
#
# This module keeps the bookkeeping that lets a piece of rendered text point
# back to the LaTeX source it came from.  It is written in the restricted
# python subset that the sources are transcribed to JavaScript in, so it does
# not use f-strings, percent-style formatting, introspection or any module that
# the JavaScript build does not provide.
#
# The bookkeeping deliberately distinguishes three kinds of origins:
#
# - Text copied straight from a characters node is 'source' text: the very
#   characters exist, in the same order, in the original TeX.
#
# - Text produced by a macro, an environment or a specials conversion is
#   'macro' text: the source range is the whole invocation.  Hitting only part
#   of the expansion still reports the whole invocation, so that nobody is led
#   to believe the original source holds an independent fragment there.
#
# - Comments that the conversion threw away are recorded on their own, as
#   'comment' records, and never mixed into the spans that cover output text.
#
# A single output position can be covered by several spans at once (an outer
# macro, a nested macro argument and the characters of that argument), and one
# source range can feed several output regions (an argument repeated by its
# replacement string): the mapping is many-to-many in both directions.


