#
# The origin kinds.  Stored as short strings so that the values read nicely in
# both python and JavaScript.
#

# characters taken verbatim from the source
SOURCE_KIND_SOURCE = 'source'
# text generated by a macro, environment or specials conversion
SOURCE_KIND_MACRO = 'macro'
# text assembled by the engine itself (joiners, list markers, filling, ...)
SOURCE_KIND_SYNTHESIZED = 'synthesized'
# text that comes from a comment (only present with keep_comments=True)
SOURCE_KIND_COMMENT = 'comment'


def _node_span_spec(kind, node):
    # A "span spec" is the deferred form of a span, before the output positions
    # are known: (kind, source pos, source pos_end, node).  The node reference
    # may be None for engine-synthesized text.
    if node is None:
        return (kind, None, None, None,)
    return (kind, node.pos, node.pos_end, node,)


def _spec_key(spec):
    # The identity of a span spec.  The node cannot be put in a hashable key
    # nor compared with '==', because LatexNode defines a structural equality
    # and no hash; identify it by its unique object id instead.
    node = spec[3]
    node_id = fn_unique_object_id(node) if node is not None else None
    return (spec[0], spec[1], spec[2], node_id,)


def _append_unique_spec(specs, spec):
    key = _spec_key(spec)
    for existing in specs:
        if _spec_key(existing) == key:
            return
    specs.append(spec)


class TextSourceSpan(object):
    r"""
    One piece of evidence about where a region of the rendered text came from.

    A span pairs a region of the rendered text (`text_pos` … `text_pos_end`,
    half-open) with a region of the original LaTeX source (`pos` … `pos_end`,
    also half-open, and `None` for synthesized text that has no source of its
    own).

    .. py:attribute:: kind

       One of the module constants :py:data:`SOURCE_KIND_SOURCE`,
       :py:data:`SOURCE_KIND_MACRO`, :py:data:`SOURCE_KIND_SYNTHESIZED` or
       :py:data:`SOURCE_KIND_COMMENT`.

    .. py:attribute:: pos
    .. py:attribute:: pos_end

       The half-open range in the original LaTeX source.  For a macro span this
       is the whole invocation, even when only a part of its expansion was
       hit.  `None` for synthesized text.

    .. py:attribute:: text_pos
    .. py:attribute:: text_pos_end

       The half-open range in the rendered text.  `None` for the records in
       :py:attr:`TextSourceInfo.discarded_comments`, which produced no output
       text.

    .. py:attribute:: node

       The parsed node the span was derived from, when there is one.  Use the
       `macroname`, `environmentname` and `specials_chars` properties to tell
       what kind of invocation a macro span refers to without having to inspect
       the node yourself.
    """

    def __init__(self, kind, pos, pos_end, text_pos, text_pos_end, node=None):
        super(TextSourceSpan, self).__init__()
        self.kind = kind
        self.pos = pos
        self.pos_end = pos_end
        self.text_pos = text_pos
        self.text_pos_end = text_pos_end
        self.node = node

    @property
    def macroname(self):
        r"""The macro name if this span comes from a macro node, else `None`."""
        node = self.node
        if node is not None \
           and node.isNodeType(latexnodes_nodes.LatexMacroNode):
            return node.macroname
        return None

    @property
    def environmentname(self):
        r"""The environment name if this span comes from an environment node."""
        node = self.node
        if node is not None \
           and node.isNodeType(latexnodes_nodes.LatexEnvironmentNode):
            return node.environmentname
        return None

    @property
    def specials_chars(self):
        r"""The specials characters if this span comes from a specials node."""
        node = self.node
        if node is not None \
           and node.isNodeType(latexnodes_nodes.LatexSpecialsNode):
            return node.specials_chars
        return None

    def source_text(self, latex_source):
        r"""Return the slice of `latex_source` that this span points at."""
        if self.pos is None:
            return None
        return latex_source[self.pos:self.pos_end]

    def __repr__(self):
        return ("TextSourceSpan(kind={!r}, source=({!r},{!r}), "
                "text=({!r},{!r}))").format(
                    self.kind, self.pos, self.pos_end,
                    self.text_pos, self.text_pos_end)


class _Frame(object):
    # One stack entry per node being converted.  A frame gathers the rendered
    # chunks of its node along with the span specs that produced them.  The
    # output positions are only resolved once the whole frame stack is built.

    def __init__(self, node, parent):
        super(_Frame, self).__init__()
        self.node = node
        self.parent = parent
        # each chunk is (rendered text, list of span specs)
        self.chunks = []

    def add_chunk(self, text, span_specs):
        if not text:
            return
        if span_specs is None:
            span_specs = []
        self.chunks.append( (text, list(span_specs),) )

    def child_text(self):
        # the text that the chunks gathered so far concatenate to
        parts = []
        for chunk in self.chunks:
            parts.append(chunk[0])
        return ''.join(parts)

    def all_child_span_specs(self):
        specs = []
        for chunk in self.chunks:
            for spec in chunk[1]:
                _append_unique_spec(specs, spec)
        return specs


class TextSourceTracker(object):
    r"""
    Accumulates the source mapping while a node tree is being converted to
    text.  One tracker is used per conversion; it is not reused.

    The converter pushes a frame around every node it renders
    (:py:meth:`begin_frame` / :py:meth:`end_frame`) and tells the tracker about
    comments it drops (:py:meth:`record_discarded_comment`).  At the end,
    :py:meth:`build()` produces the immutable :py:class:`TextSourceInfo`.
    """

    def __init__(self):
        super(TextSourceTracker, self).__init__()
        # the root frame stands for the whole node list of the conversion
        self._root = _Frame(node=None, parent=None)
        self._current = self._root
        self._discarded_comment_specs = []

    # -- frame handling ------------------------------------------------------

    def begin_frame(self, node):
        frame = _Frame(node=node, parent=self._current)
        self._current = frame

    def end_frame(self, node, result):
        frame = self._current
        # the converter pushes and pops around node_to_text(), so the frame on
        # top must be the one for this very node
        if frame.node is not node:
            raise RuntimeError(
                "TextSourceTracker frame mismatch: expected {!r}, got {!r}"
                .format(frame.node, node)
            )
        parent = frame.parent
        chunks = self._close_frame_chunks(frame, node, result)
        self._current = parent
        for chunk in chunks:
            parent.add_chunk(chunk[0], chunk[1])

    def _close_frame_chunks(self, frame, node, result):
        # Decide which chunks the frame hands to its parent.  Returns a list of
        # (text, span specs).

        if node is None:
            # the root frame keeps its chunks as they are
            return frame.chunks

        is_invocation = (
            node.isNodeType(latexnodes_nodes.LatexMacroNode)
            or node.isNodeType(latexnodes_nodes.LatexEnvironmentNode)
            or node.isNodeType(latexnodes_nodes.LatexSpecialsNode)
        )

        if is_invocation:
            # a simplify_repl in the fancy math engine may hand back a math
            # piece rather than a string; its rendered text is all we can align
            if not isinstance(result, str):
                result = str(result)
            return self._close_invocation_frame(frame, node, result)

        if not isinstance(result, str):
            # any other non-string rendering: attribute the whole thing coarsely
            return self._coarse_chunks(result, frame, node)

        if node.isNodeType(latexnodes_nodes.LatexCharsNode):
            # characters taken straight from the source; any dropping of
            # whitespace or font styling only ever shortens the rendering
            if result:
                return [ (result, [_node_span_spec(SOURCE_KIND_SOURCE, node),],) ]
            return []

        if node.isNodeType(latexnodes_nodes.LatexCommentNode):
            # A kept comment is rendered whole, including the '%'.  A dropped
            # comment renders nothing itself; the only text that can survive
            # it is the whitespace that followed it (comment_post_space),
            # which is part of the comment node's own source range.  Point
            # that surviving whitespace at its exact source sub-range rather
            # than at the comment text.
            if not result:
                return []
            if result[0:1] == '%':
                return [ (result,
                          [_node_span_spec(SOURCE_KIND_COMMENT, node),],) ]
            post_space = node.comment_post_space
            if post_space and result.endswith(post_space):
                sub_start = node.pos_end - len(post_space)
                spec = (SOURCE_KIND_SOURCE, sub_start, node.pos_end, node,)
                return [ (result, [spec,],) ]
            return [ (result,
                      [_node_span_spec(SOURCE_KIND_COMMENT, node),],) ]

        if node.isNodeType(latexnodes_nodes.LatexMathNode):
            # The fancy math engine inserts spaces and may reorder a
            # superscript and a subscript, so inner positions cannot always be
            # aligned.  Place the child renderings wherever they survive
            # verbatim, and cover everything else by a coarse span over the
            # whole math node; never invent a fragment that the source does
            # not contain.
            if not result:
                return []
            outer_spec = _node_span_spec(SOURCE_KIND_SOURCE, node)
            child_chunks = [ chunk for chunk in frame.chunks if chunk[0] ]
            if child_chunks:
                placed = self._place_chunks(result, child_chunks, outer_spec)
                if placed is not None:
                    return placed
            return [ (result, [outer_spec,],) ]

        if node.isNodeType(latexnodes_nodes.LatexGroupNode):
            # groups are transparent while the braces are dropped; if the
            # delimiters are kept (keep_braced_groups) the result no longer
            # matches the concatenation of the children, so attribute the
            # whole group coarsely
            if result and result == frame.child_text():
                return frame.chunks
            if result:
                return [ (result, [_node_span_spec(SOURCE_KIND_SOURCE, node),],) ]
            return []

        # any other node type: pass the children's chunks through unchanged
        return frame.chunks

    def _close_invocation_frame(self, frame, node, result):
        # The frame of a macro, an environment or a specials conversion.  The
        # whole result is covered by a span over the entire invocation; on top
        # of that we place the rendered arguments at the exact output positions
        # where the replacement text embedded them.
        outer_spec = _node_span_spec(SOURCE_KIND_MACRO, node)

        if not result:
            return []

        child_chunks = [ chunk for chunk in frame.chunks if chunk[0] ]
        if not child_chunks:
            # a pure literal replacement, such as MacroTextSpec('LaTeX', ...):
            # the output is attributed to the invocation and to nothing else
            return [ (result, [outer_spec,],) ]

        # Locate every argument rendering inside the replacement text,
        # including an argument that the replacement repeats.  A callable that
        # rewrites or reorders its arguments defeats the alignment, in which
        # case we fall back onto the coarse invocation span rather than
        # guessing positions.
        placed = self._place_chunks(result, child_chunks, outer_spec)
        if placed is not None:
            return placed
        return self._coarse_invocation_fallback(frame, outer_spec, result)

    def _place_chunks(self, result, child_chunks, outer_spec):
        # Place the child renderings inside `result`, allowing the same
        # rendering to occur more than once (an argument repeated by its
        # replacement string).  Returns the new chunk list, or None if the
        # ordered set of child renderings cannot be matched.  Every region of
        # `result` stays covered by `outer_spec`, so an unmatched region is
        # still attributed to the surrounding invocation or formula.

        # First pass: every child rendering is placed once, in order and
        # without crossings.  This is what makes a reordered or rewritten
        # argument detectable, so that we refuse to guess in that case.
        precise = []  # (start, end, span specs)
        search_from = 0
        for chunk_text, chunk_specs in child_chunks:
            idx = result.find(chunk_text, search_from)
            if idx < 0:
                return None
            precise.append( (idx, idx + len(chunk_text),
                             [outer_spec,] + list(chunk_specs),) )
            search_from = idx + len(chunk_text)

        # Second pass: an argument may be embedded several times.  Find every
        # other verbatim occurrence of a child rendering and give that region
        # the same precise attribution, as long as it does not overlap a
        # region that the first pass already explained.
        for chunk_text, chunk_specs in child_chunks:
            find_from = 0
            while True:
                idx = result.find(chunk_text, find_from)
                if idx < 0:
                    break
                end = idx + len(chunk_text)
                if not self._region_intersects_precise(precise, idx, end):
                    precise.append( (idx, end,
                                     [outer_spec,] + list(chunk_specs),) )
                find_from = end

        # insertion sort by output start position; written explicitly (and
        # without sort(key=...)) to stay within the JavaScript-compatible
        # subset of python
        for i in range(1, len(precise)):
            region = precise[i]
            j = i - 1
            while j >= 0 and precise[j][0] > region[0]:
                precise[j+1] = precise[j]
                j = j - 1
            precise[j+1] = region

        # Fill the gaps between the precisely attributed regions; those hold
        # text that only the surrounding span can account for.
        placed = []
        cursor = 0
        for start, end, specs in precise:
            if start > cursor:
                placed.append( (result[cursor:start], [outer_spec,],) )
            placed.append( (result[start:end], specs,) )
            cursor = end
        if cursor < len(result):
            placed.append( (result[cursor:], [outer_spec,],) )
        return placed

    def _region_intersects_precise(self, precise, start, end):
        for region_start, region_end, specs in precise:
            if start < region_end and region_start < end:
                return True
        return False

    def _coarse_invocation_fallback(self, frame, outer_spec, result):
        # The argument renderings could not be located inside the replacement
        # text.  Keep every child span as evidence, but covering the whole
        # output of the invocation, alongside the invocation span itself.
        specs = [outer_spec,] + frame.all_child_span_specs()
        return [ (result, specs,) ]

    def _coarse_chunks(self, result, frame, node):
        if not result:
            return []
        return [ (str(result),
                  [_node_span_spec(SOURCE_KIND_SOURCE, node),],) ]

    # -- comments ------------------------------------------------------------

    def record_discarded_comment(self, node):
        r"""Record a comment node that the conversion did not keep."""
        spec = _node_span_spec(SOURCE_KIND_COMMENT, node)
        _append_unique_spec(self._discarded_comment_specs, spec)

    # -- direct emissions ----------------------------------------------------

    def emit_text(self, text, node=None, kind=SOURCE_KIND_SYNTHESIZED):
        # Text emitted outside of a node frame's own rendering, such as the
        # post-macro space that nodelist_to_text() re-inserts in non-strict
        # mode.  Without a node this is plain synthesized text.
        if not text:
            return
        specs = []
        if node is not None:
            specs.append(_node_span_spec(kind, node))
        self._current.add_chunk(text, specs)

    # -- build ---------------------------------------------------------------

    def coerce_root_to_text(self, text):
        r"""
        Replace the root chunks by a single chunk covering all of `text`.

        Used when the top-level conversion returned a math piece rather than a
        string, so that the piece's joined rendering cannot be aligned with the
        per-node chunks any more.  All the evidence gathered so far is kept, but
        it now covers the whole rendered text conservatively instead of pointing
        at positions that the joiner may have moved.
        """
        specs = self._root.all_child_span_specs()
        if text:
            self._root.chunks = [ (text, specs,) ]
        else:
            self._root.chunks = []

    def build(self, expected_text):
        if self._current is not self._root:
            raise RuntimeError(
                "TextSourceTracker.build(): some frames are still open"
            )

        spans = []
        text_parts = []
        cursor = 0
        for chunk_text, chunk_specs in self._root.chunks:
            text_start = cursor
            text_end = cursor + len(chunk_text)
            for spec in chunk_specs:
                spans.append(TextSourceSpan(
                    kind=spec[0],
                    pos=spec[1],
                    pos_end=spec[2],
                    text_pos=text_start,
                    text_pos_end=text_end,
                    node=spec[3],
                ))
            text_parts.append(chunk_text)
            cursor = text_end

        rendered_text = ''.join(text_parts)
        if rendered_text != expected_text:
            # The tracker is supposed to mirror exactly what the renderer
            # emitted.  A mismatch is a bug in the integration, not a user
            # error: fail loudly rather than hand back misaligned spans.
            raise RuntimeError(
                "TextSourceTracker: rendered text mismatch (got {!r}, "
                "expected {!r})".format(rendered_text, expected_text)
            )

        discarded = []
        for spec in self._discarded_comment_specs:
            discarded.append(TextSourceSpan(
                kind=spec[0],
                pos=spec[1],
                pos_end=spec[2],
                text_pos=None,
                text_pos_end=None,
                node=spec[3],
            ))

        return TextSourceInfo(text=rendered_text, spans=spans,
                              discarded_comments=discarded)


class TextSourceInfo(object):
    r"""
    The source mapping of one converted text.

    Returned by
    :py:meth:`~pylatexenc.latex2text.LatexNodes2Text.latex_to_text_with_source_info()`
    and the matching node-list method.  The object is immutable as far as
    calling code is concerned.

    .. py:attribute:: text

       The rendered plain text, identical to what the plain conversion returns.

    .. py:attribute:: spans

       All the :py:class:`TextSourceSpan` objects that cover regions of the
       rendered text, in emission order.  A single output position is usually
       covered by more than one span.

    .. py:attribute:: discarded_comments

       Spans of kind :py:data:`SOURCE_KIND_COMMENT` for comments that were
       dropped during the conversion.  Their `text_pos` is `None` because they
       produced no output text; they are kept apart from `spans` so that a
       dropped comment can never be mistaken for the source of some output.
    """

    def __init__(self, text, spans, discarded_comments):
        super(TextSourceInfo, self).__init__()
        self.text = text
        self.spans = spans
        self.discarded_comments = discarded_comments

    def _span_matches(self, span, seen):
        # Identity of a span for de-duplication: same kind, source range and
        # node.  Two output regions may legitimately share one such identity
        # (an argument repeated by its replacement string).
        node = span.node
        node_id = fn_unique_object_id(node) if node is not None else None
        key = (span.kind, span.pos, span.pos_end, node_id,)
        if key in seen:
            return False
        seen.append(key)
        return True

    def sources_at(self, text_pos):
        r"""
        Return the spans that cover the character at `text_pos` in the rendered
        text.  The outermost invocation comes first and the most specific
        origin last, so a caller can simply take the first or the last entry
        depending on whether it wants the whole macro call or the innermost
        characters.
        """
        matches = []
        seen = []
        for span in self.spans:
            if span.text_pos is None:
                continue
            if text_pos >= span.text_pos and text_pos < span.text_pos_end:
                if self._span_matches(span, seen):
                    matches.append(span)
        return matches

    def sources_for_range(self, text_start, text_end):
        r"""
        Return the spans that intersect the half-open rendered-text region
        [`text_start`, `text_end`).
        """
        matches = []
        seen = []
        for span in self.spans:
            if span.text_pos is None:
                continue
            if span.text_pos_end <= text_start or span.text_pos >= text_end:
                continue
            if self._span_matches(span, seen):
                matches.append(span)
        return matches

    def source_ranges_at(self, text_pos):
        r"""
        Return the distinct half-open source ranges `(pos, pos_end)` that
        cover the rendered-text position `text_pos`.  Synthesized spans, whose
        source position is `None`, are skipped.
        """
        ranges = []
        for span in self.sources_at(text_pos):
            if span.pos is None:
                continue
            pair = (span.pos, span.pos_end,)
            if pair not in ranges:
                ranges.append(pair)
        return ranges

    def macro_spans(self):
        r"""Return the macro/environment/specials spans, in emission order."""
        return [ span for span in self.spans if span.kind == SOURCE_KIND_MACRO ]

    def __repr__(self):
        return ("TextSourceInfo(text={!r}, num_spans={}, "
                "num_discarded_comments={})").format(
                    self.text, len(self.spans), len(self.discarded_comments))
